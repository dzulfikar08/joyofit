// Type-checks the JS shapes the iOS module returns (dumped by InertStatusTests.testDumpShapesForTheTypeScriptCheck) against the real
// TypeScript declarations in modules/huawei-wear/src. Usage (from the repo root):
//
//   INERT_SHAPES_OUT=/tmp/shapes.json swift test --package-path modules/huawei-wear/ios/ModuleLogicTests --filter testDumpShapes
//   node modules/huawei-wear/ios/ModuleLogicTests/check-inert-shapes.mjs /tmp/shapes.json
//
// Each shape becomes an object literal assigned to its interface, so a missing field, a misnamed field, an extra field and a wrong literal type
// (`fallSwitch: -1 | 0 | 1`) are all compile errors.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..', '..');
// A feature's own tests may dump their shapes next to the main file as `<name>.<feature>.json` (shapes.json -> shapes.huawei-import.json);
// they are checked together with it.
const main = process.argv[2];
const stem = basename(main, '.json');
const extras = readdirSync(dirname(main)).filter((f) => f.startsWith(`${stem}.`) && f.endsWith('.json')).map((f) => join(dirname(main), f));
const shapes = Object.assign({}, ...[main, ...extras].map((f) => JSON.parse(readFileSync(f, 'utf8'))));

const sources = {
  PhoneFeatures: 'HuaweiWearPhone.types',
  WatchAlarms: 'HuaweiWearPhone.types',
  SafetyStatus: 'HuaweiWearExtras.types',
  SosRelayTest: 'HuaweiWearExtras.types',
  AgpsStatus: 'HuaweiWearExtras.types',
  CycleOverview: 'HuaweiWearExtras.types',
  ActivityGoalsStatus: 'HuaweiWearDiet.types',
  BodyMetrics: 'HuaweiWearDiet.types',
  DietStatus: 'HuaweiWearDiet.types',
  HealthyLivingStatus: 'HuaweiWearP2p.types',
  CoursesStatus: 'HuaweiWearP2p.types',
  HuaweiImportSummary: 'HuaweiWearImport.types',
  HuaweiImportProgressEvent: 'HuaweiWearImport.types',
  RunningCoursePushResult: 'HuaweiWearP2p.types',
  RoutesStatus: 'HuaweiWearRoutes.types',
  OfflineMapLabStatus: 'HuaweiWearOfflineMaps.types',
  RoutePushResult: 'HuaweiWearRoutes.types',
  NotificationFilterStatus: 'HuaweiWearNotifications.types',
  NotificationFilterTest: 'HuaweiWearNotifications.types',
};
const core = 'HuaweiWear.types';

let code = '// generated by check-inert-shapes.mjs\n';
// "Name#variant" checks a second value against the same interface (a status with nothing set, and one with everything set).
const typeOf = (key) => key.split('#')[0];
const varOf = (key) => key.replace('#', '_').replace(/^./, (c) => c.toLowerCase());
for (const name of new Set(Object.keys(shapes).map(typeOf))) {
  const from = sources[name] ?? core;
  code += `import type { ${name} } from '../../../src/${from}';\n`;
}
for (const [key, value] of Object.entries(shapes)) {
  code += `export const ${varOf(key)}: ${typeOf(key)} = ${JSON.stringify(value, null, 2)};\n`;
}
const out = join(here, '.inert-check');
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'shapes.check.ts'), code);
writeFileSync(
  join(out, 'tsconfig.json'),
  JSON.stringify({
    compilerOptions: { strict: true, noEmit: true, target: 'ES2020', module: 'ESNext', moduleResolution: 'bundler', skipLibCheck: true, types: [] },
    files: ['shapes.check.ts'],
  }),
);
const tsrs = join(root, 'node_modules', '.bin', 'tsrs');
try {
  execFileSync(tsrs, ['-p', join(out, 'tsconfig.json')], { stdio: 'inherit' });
  console.log(`OK: ${Object.keys(shapes).length} shapes match their TypeScript types (${Object.keys(shapes).join(', ')})`);
} catch {
  process.exit(1);
}
