// Generates src/rogo/metrics.ts: per-weight advance-width tables measured in Chromium.
// Run: bun packages/sticker/scripts/gen-metrics.ts
// Mono font: `npm pack @expo-google-fonts/ibm-plex-mono`, extract, and point PLEX_MONO_DIR
// at the extracted `package` dir (containing 400Regular/, 500Medium/, 700Bold/).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "../../..");
const SANS_DIR =
  process.env.JAKARTA_DIR ??
  join(ROOT, "node_modules/.bun/@expo-google-fonts+plus-jakarta-sans@0.4.2/node_modules/@expo-google-fonts/plus-jakarta-sans");
const MONO_DIR = process.env.PLEX_MONO_DIR ?? "/run/media/dzul/ioswork/tmp/plex/package";

const SANS_FILES: Record<number, string> = {
  500: join(SANS_DIR, "500Medium/PlusJakartaSans_500Medium.ttf"),
  600: join(SANS_DIR, "600SemiBold/PlusJakartaSans_600SemiBold.ttf"),
  700: join(SANS_DIR, "700Bold/PlusJakartaSans_700Bold.ttf"),
  800: join(SANS_DIR, "800ExtraBold/PlusJakartaSans_800ExtraBold.ttf"),
};
const MONO_FILES: Record<number, string> = {
  400: join(MONO_DIR, "400Regular/IBMPlexMono_400Regular.ttf"),
  500: join(MONO_DIR, "500Medium/IBMPlexMono_500Medium.ttf"),
  700: join(MONO_DIR, "700Bold/IBMPlexMono_700Bold.ttf"),
};

const START = 32;
const END = 0x24f;
const EXTRA = [0x2010, 0x2011, 0x2012, 0x2013, 0x2014, 0x2015, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0x2212, 0xd7, 0x2192, 0x2191, 0x2193];

type Spec = { kind: "sans" | "mono"; weight: number; file: string };
const specs: Spec[] = [
  ...Object.entries(SANS_FILES).map(([w, file]) => ({ kind: "sans" as const, weight: +w, file })),
  ...Object.entries(MONO_FILES).map(([w, file]) => ({ kind: "mono" as const, weight: +w, file })),
];

const { chromium } = await import(join(ROOT, "node_modules/playwright"));
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
const page = await browser.newPage();
await page.setContent("<html><body></body></html>");

const faces = specs.map((s, i) => ({ name: `F${i}`, b64: readFileSync(s.file).toString("base64") }));
const raw: any[] = await page.evaluate(
  async ({ faces, START, END, EXTRA }: { faces: { name: string; b64: string }[]; START: number; END: number; EXTRA: number[] }) => {
    const out: any[] = [];
    for (const f of faces) {
      const ff = new FontFace(f.name, `url(data:font/ttf;base64,${f.b64})`);
      document.fonts.add(await ff.load());
      await document.fonts.load(`100px "${f.name}"`);
      const ctx = document.createElement("canvas").getContext("2d")!;
      ctx.fontKerning = "none";
      const m = (font: string, ch: string) => {
        ctx.font = font;
        return ctx.measureText(ch);
      };
      const own = `1000px "${f.name}"`;
      const serif = `1000px "${f.name}", serif`;
      const mono = `1000px "${f.name}", monospace`;
      // A glyph is absent when the fallback family changes the measured width.
      const has = (ch: string) => m(serif, ch).width === m(mono, ch).width;
      const adv = (cp: number) => Math.round(m(own, String.fromCodePoint(cp)).width);
      const space = adv(32);
      const w: number[] = [];
      for (let cp = START; cp <= END; cp++) {
        w.push(has(String.fromCodePoint(cp)) ? adv(cp) : space);
      }
      const extra: Record<number, number> = {};
      for (const cp of EXTRA) if (has(String.fromCodePoint(cp))) extra[cp] = adv(cp);
      const mm = m(own, "H");
      out.push({
        asc: mm.fontBoundingBoxAscent / 1000,
        desc: mm.fontBoundingBoxDescent / 1000,
        cap: mm.actualBoundingBoxAscent / 1000,
        xh: m(own, "x").actualBoundingBoxAscent / 1000,
        w,
        extra,
      });
    }
    return out;
  },
  { faces, START, END, EXTRA },
);
await browser.close();

const r3 = (n: number) => Math.round(n * 1000) / 1000;
const table = (r: any) => {
  let sum = 0;
  let n = 0;
  for (let cp = 0x30; cp <= 0x7a; cp++) {
    if ((cp >= 0x30 && cp <= 0x39) || (cp >= 0x41 && cp <= 0x5a) || (cp >= 0x61 && cp <= 0x7a)) {
      sum += r.w[cp - START];
      n++;
    }
  }
  const extra = Object.entries(r.extra).map(([k, v]) => `${k}: ${v}`).join(", ");
  return `{ asc: ${r3(r.asc)}, desc: ${r3(r.desc)}, cap: ${r3(r.cap)}, xh: ${r3(r.xh)}, avg: ${r3(sum / n)}, start: ${START}, w: [${r.w.join(",")}], extra: {${extra}} }`;
};
const block = (kind: string) =>
  specs.map((s, i) => (s.kind === kind ? `  ${s.weight}: ${table(raw[i])},` : "")).filter(Boolean).join("\n");

const src = `import type { FontTable } from "../core/text";
// Generated by scripts/gen-metrics.ts from the font files. Do not edit.
export const SANS: Record<number, FontTable> = {
${block("sans")}
};
export const MONO: Record<number, FontTable> = {
${block("mono")}
};
`;
writeFileSync(join(import.meta.dir, "../src/rogo/metrics.ts"), src);
console.log("wrote metrics.ts");
